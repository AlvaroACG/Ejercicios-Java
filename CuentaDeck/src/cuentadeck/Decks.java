    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        int coreP = Integer.parseInt(txfCant.getText()); 
        int staplesP = Integer.parseInt(txfStap.getText());
        String protector = cmbxTipo.getSelectedItem().toString();
        String arquetipo = txfArq.getText();

        int totalCartas = coreP + staplesP;
        int totalProtectores = 0;

        if (totalCartas >= 40 && totalCartas <= 60) {

            if ("Simples".equals(protector)) {
                totalProtectores = totalCartas;
            } else {
                totalProtectores = totalCartas * 2;
            }

            ConexionDeck gc = new ConexionDeck();

            try {
                Connection cn = gc.obtieneConexion();
                PreparedStatement ps = cn.prepareStatement("INSERT INTO mazos (arquetipo, core, staple, protector, totalProtectores, totalCartas) VALUES (?, ?, ?, ?, ?, ?)");

                ps.setString(1, arquetipo);
                ps.setInt(2, coreP);
                ps.setInt(3, staplesP);
                ps.setString(4, protector);
                ps.setInt(5, totalProtectores);
                ps.setInt(6, totalCartas);

                int resultado = ps.executeUpdate();

                if (resultado > 0) {
                    JOptionPane.showMessageDialog(this, "Deck válido registrado en la base de datos correctamente.");
                    cargarTabla();
                } else {
                    JOptionPane.showMessageDialog(this, "Fallo el registro del deck.", "Error", JOptionPane.ERROR_MESSAGE);
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al guardar en base de datos: " + e, "Error SQL", JOptionPane.ERROR_MESSAGE);
            }

        } else {
            JOptionPane.showMessageDialog(this, "Total de cartas no permitido", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnRegistrarActionPerformed
    
    public void cargarTabla() {
    
        DefaultTableModel mt = new DefaultTableModel();
        String enca[] = {"ID", "Arquetipo", "Core", "Staples", "Protector", "Total Protectores", "Total Cartas"};
        mt.setColumnIdentifiers(enca);
        tblDecks.setModel(mt);

        ConexionDeck gc = new ConexionDeck();

        try {
            Connection cn = gc.obtieneConexion();
            PreparedStatement ps = cn.prepareStatement("SELECT idDeck, arquetipo, core, staple, protector, totalProtectores, totalCartas FROM mazos");

            ResultSet rs = ps.executeQuery();

            while (rs.next()) {

                // Llenando la tabla con el resultado de la consulta de mazos
                mt.addRow(new Object[] {
                    rs.getInt("idDeck"), 
                    rs.getString("arquetipo"), 
                    rs.getInt("core"), 
                    rs.getInt("staple"), 
                    rs.getString("protector"), 
                    rs.getInt("totalProtectores"), 
                    rs.getInt("totalCartas")
                });

            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar la tabla: " + e, "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    
